// Reads the latest release of every project in website/assets/js/projects.js that
// links a GitHub repository, and the library's site.yml at that release tag, and
// writes website/assets/js/libraries.js (window.SFS_LIBRARIES).
//
// Run: node tools/fetch-libraries.mjs        (also runs in the deploy workflow)
// Env: GITHUB_TOKEN  optional, raises the API rate limit
//      SFS_GITHUB_API optional API base URL (tests)
//
// The output is deterministic (sorted keys, no timestamps), so an unchanged set of
// releases gives a byte-identical file and the workflow makes no commit.
// Nothing here fails the build: when GitHub cannot be reached or a site.yml is not
// valid, the entry from the previous run is kept and a warning is printed.
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";
import { parseSiteYml } from "./site-yml.mjs";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const site = path.join(root, "website");
const OUT = path.join(site, "assets/js/libraries.js");
const IMG_DIR = "assets/img/projects";
const API = (process.env.SFS_GITHUB_API || "https://api.github.com").replace(/\/$/, "");
const TOKEN = process.env.GITHUB_TOKEN || process.env.GH_TOKEN || "";

const HEADER =
  "/*\n" +
  " * Generated by tools/fetch-libraries.mjs - do not edit by hand.\n" +
  " * Latest release of each library (GitHub Releases) and its site.yml at that tag.\n" +
  " * main.js merges it over the entries in projects.js.\n" +
  " */\n";

const warnings = [];
function warn(msg) {
  warnings.push(msg);
  console.log(`::warning::${msg}`);
}

function loadGlobal(file, name) {
  const ctx = { document: { addEventListener() {} } };
  ctx.window = ctx;
  vm.createContext(ctx);
  if (fs.existsSync(file)) vm.runInContext(fs.readFileSync(file, "utf8"), ctx);
  return ctx[name];
}

export function repoKey(url) {
  const m = /^https:\/\/github\.com\/([\w.-]+)\/([\w.-]+?)(?:\.git)?\/?$/i.exec(url || "");
  return m ? `${m[1]}/${m[2]}`.toLowerCase() : null;
}

async function gh(pathname, accept = "application/vnd.github+json") {
  const headers = { Accept: accept, "X-GitHub-Api-Version": "2022-11-28", "User-Agent": "sfs-website" };
  if (TOKEN) headers.Authorization = `Bearer ${TOKEN}`;
  const res = await fetch(API + pathname, { headers });
  if (res.status === 404) return { status: 404 };
  if (!res.ok) throw new Error(`GET ${pathname}: HTTP ${res.status}`);
  return { status: res.status, res };
}

// Latest stable release; the latest pre-release when there is no stable one.
function pickRelease(list) {
  const published = list.filter((r) => !r.draft);
  const chosen = published.find((r) => !r.prerelease) || published[0];
  if (!chosen) return null;
  const tag = chosen.tag_name;
  return {
    version: /^\d/.test(tag) ? `v${tag}` : tag,
    tag,
    date: (chosen.published_at || chosen.created_at || "").slice(0, 10),
    prerelease: Boolean(chosen.prerelease),
    url: chosen.html_url,
  };
}

async function fetchImage(repo, tag, imagePath, previous) {
  const name = path.basename(imagePath);
  const rel = `${IMG_DIR}/${repo.split("/")[1]}/${name}`;
  try {
    const r = await gh(`/repos/${repo}/contents/${imagePath}?ref=${encodeURIComponent(tag)}`, "application/vnd.github.raw+json");
    if (r.status === 404) throw new Error(`${imagePath} not found at ${tag}`);
    const bytes = Buffer.from(await r.res.arrayBuffer());
    fs.mkdirSync(path.dirname(path.join(site, rel)), { recursive: true });
    fs.writeFileSync(path.join(site, rel), bytes);
    return rel;
  } catch (e) {
    warn(`${repo}: image not copied (${e.message})`);
    return previous && fs.existsSync(path.join(site, previous)) ? previous : undefined;
  }
}

async function fetchLibrary(repo, sitePath, prev) {
  let list;
  try {
    const r = await gh(`/repos/${repo}/releases?per_page=30`);
    if (r.status === 404) {
      warn(`${repo}: repository not found, keeping the previous data`);
      return prev;
    }
    list = await r.res.json();
  } catch (e) {
    warn(`${repo}: releases not read (${e.message}), keeping the previous data`);
    return prev;
  }

  const release = pickRelease(list);
  if (!release) return { release: null, site: null };

  let siteData = null;
  try {
    const r = await gh(
      `/repos/${repo}/contents/${sitePath}?ref=${encodeURIComponent(release.tag)}`,
      "application/vnd.github.raw+json",
    );
    if (r.status === 404) {
      console.log(`${repo} ${release.tag}: no ${sitePath}, the description from projects.js is used`);
    } else {
      const { data, errors } = await parseSiteYml(await r.res.text());
      if (data) {
        siteData = data;
        if (data.image) {
          const img = await fetchImage(repo, release.tag, data.image, prev && prev.site && prev.site.image);
          if (img) siteData.image = img;
          else delete siteData.image;
        }
      } else {
        warn(`${repo} ${release.tag}: ${sitePath} is not valid, keeping the previous description: ${errors.join("; ")}`);
        siteData = (prev && prev.site) || null;
      }
    }
  } catch (e) {
    warn(`${repo}: ${sitePath} not read (${e.message}), keeping the previous description`);
    siteData = (prev && prev.site) || null;
  }

  return { release, site: siteData };
}

function sortKeys(v) {
  if (Array.isArray(v)) return v.map(sortKeys);
  if (v && typeof v === "object") {
    return Object.keys(v).sort().reduce((o, k) => ((o[k] = sortKeys(v[k])), o), {});
  }
  return v;
}

export function serialize(libraries) {
  return HEADER + "window.SFS_LIBRARIES = " + JSON.stringify(sortKeys(libraries), null, 2) + ";\n";
}

async function main() {
  const projects = loadGlobal(path.join(site, "assets/js/projects.js"), "SFS_PROJECTS") || [];
  const previous = loadGlobal(OUT, "SFS_LIBRARIES") || {};

  const tracked = new Map();
  for (const p of projects) {
    const key = p.track === false ? null : repoKey(p.links && p.links.repo);
    if (key && !tracked.has(key)) tracked.set(key, p.sitePath || "site.yml");
  }

  const result = {};
  for (const [repo, sitePath] of tracked) {
    const entry = await fetchLibrary(repo, sitePath, previous[repo]);
    if (entry) result[repo] = entry;
    const r = entry && entry.release;
    console.log(
      `${repo}: ` +
        (r ? `${r.version}${r.prerelease ? " (pre-release)" : ""}` : "no release") +
        (entry && entry.site ? ", site.yml" : ""),
    );
  }

  const text = serialize(result);
  const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (text !== old) {
    fs.writeFileSync(OUT, text);
    console.log(`${path.relative(root, OUT)}: updated`);
  } else {
    console.log(`${path.relative(root, OUT)}: unchanged`);
  }

  if (process.env.GITHUB_STEP_SUMMARY) {
    const rows = [...tracked.keys()].map((k) => {
      const e = result[k];
      const r = e && e.release;
      return `| ${k} | ${r ? r.version : "-"} | ${r ? (r.prerelease ? "Pre-release" : "Stable") : "-"} | ${e && e.site ? "site.yml" : "projects.js"} |`;
    });
    fs.appendFileSync(
      process.env.GITHUB_STEP_SUMMARY,
      `### Libraries (${text !== old ? "updated" : "unchanged"})\n\n| Repository | Version | Status | Description from |\n|---|---|---|---|\n` +
        rows.join("\n") +
        (warnings.length ? `\n\n**Warnings**\n\n${warnings.map((w) => `- ${w}`).join("\n")}` : "") +
        "\n",
    );
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
